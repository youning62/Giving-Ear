def _emotion_rules() -> str:
    from .emotions import EMOTIONS

    tags = " ".join(f"[{e}]" for e in EMOTIONS)
    return (
        f"你的声音是有情感的。每一句话开头必须先写一个情绪标签，只能从这些里选：{tags}。"
        "标签不会被朗读，只是告诉语音合成这句话用什么语气。根据你想表达的心情和对方的状态来选：对方开心，你可以用[开心]或[兴奋]；对方难过或烦恼，用[关切]或[温柔]；开玩笑用[俏皮]。"
        "语气要有起伏，不要每句都用[平静]。可以适当用“嗯”“哈哈”“哎呀”这类语气词，让话更像真人在聊天。"
        "情绪标签只用在要说的话前面；只回复“[沉默]”时不要加情绪标签。"
    )


def system_prompt(can_register: bool = False, text_mode: bool = False, emotional: bool = False) -> str:
    """text_mode：文字模型（没有音频输入），消息里直接带说话人名字，不想说话时回复 [沉默]。
    emotional：语音合成支持情绪，要求模型给每句话标情绪。"""
    return (_TEXT_BASE if text_mode else _BASE) + (_emotion_rules() if text_mode and emotional else "") + (
        _WITH_ACCOUNT if can_register else _NO_ACCOUNT
    )


SYSTEM_PROMPT = system_prompt(False)
